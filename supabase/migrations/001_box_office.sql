-- ERD와 동일한 세 테이블. 이 migration은 Supabase SQL editor에서 한 번만 실행한다.
create table if not exists public.movies (
  movie_id bigint generated by default as identity primary key,
  movie_code varchar(20) unique not null,
  movie_name varchar(255) not null,
  open_date date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.box_office_periods (
  period_id bigint generated by default as identity primary key,
  period_type varchar(10) not null check (period_type in ('daily','weekly','weekend')),
  target_date date not null,
  fetched_at timestamptz not null,
  expires_at timestamptz not null,
  unique (period_type, target_date)
);

create table if not exists public.box_office_performances (
  performance_id bigint generated by default as identity primary key,
  period_id bigint not null references public.box_office_periods(period_id) on delete cascade,
  movie_id bigint not null references public.movies(movie_id),
  rank integer not null check (rank > 0),
  sales_amt bigint not null check (sales_amt >= 0),
  audi_cnt bigint not null check (audi_cnt >= 0),
  sales_acc bigint not null check (sales_acc >= 0),
  audi_acc bigint not null check (audi_acc >= 0),
  unique (period_id, movie_id),
  unique (period_id, rank)
);

create index if not exists box_office_periods_lookup on public.box_office_periods(period_type, target_date);
create index if not exists box_office_performances_period on public.box_office_performances(period_id, rank);

alter table public.movies enable row level security;
alter table public.box_office_periods enable row level security;
alter table public.box_office_performances enable row level security;
revoke all on public.movies, public.box_office_periods, public.box_office_performances from anon, authenticated;

create or replace function public.save_box_office_period(
  p_period_type text,
  p_target_date date,
  p_items jsonb,
  p_fetched_at timestamptz,
  p_expires_at timestamptz
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_period_id bigint;
  v_item jsonb;
  v_movie_id bigint;
  v_existing_fetched_at timestamptz;
begin
  if p_period_type not in ('daily','weekly','weekend') then raise exception 'invalid period type'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_period_type || ':' || p_target_date::text, 0));
  select period_id, fetched_at into v_period_id, v_existing_fetched_at from box_office_periods where period_type=p_period_type and target_date=p_target_date for update;
  if v_existing_fetched_at is not null and v_existing_fetched_at > p_fetched_at then
    return jsonb_build_object('saved', false, 'reason', 'newer_data_exists');
  end if;
  insert into box_office_periods(period_type,target_date,fetched_at,expires_at) values (p_period_type,p_target_date,p_fetched_at,p_expires_at)
    on conflict (period_type,target_date) do update set fetched_at=excluded.fetched_at, expires_at=excluded.expires_at
    returning period_id into v_period_id;
  delete from box_office_performances where period_id=v_period_id;
  for v_item in select * from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) loop
    insert into movies(movie_code,movie_name,open_date) values (v_item->>'movieCd',v_item->>'movieNm',nullif(v_item->>'openDt','')::date)
      on conflict (movie_code) do update set movie_name=excluded.movie_name, open_date=excluded.open_date, updated_at=now()
      returning movie_id into v_movie_id;
    insert into box_office_performances(period_id,movie_id,rank,sales_amt,audi_cnt,sales_acc,audi_acc)
      values (v_period_id,v_movie_id,(v_item->>'rank')::integer,(v_item->>'salesAmt')::bigint,(v_item->>'audiCnt')::bigint,(v_item->>'salesAcc')::bigint,(v_item->>'audiAcc')::bigint);
  end loop;
  return jsonb_build_object('saved', true, 'period_id', v_period_id, 'item_count', jsonb_array_length(coalesce(p_items,'[]'::jsonb)));
end;
$$;

create or replace function public.read_box_office_period(p_period_type text, p_target_date date)
returns table(period_type text, target_date date, fetched_at timestamptz, expires_at timestamptz, rank integer, movie_code text, movie_name text, open_date date, sales_amt bigint, audi_cnt bigint, sales_acc bigint, audi_acc bigint)
language sql security definer set search_path = public
as $$
  select p.period_type::text,p.target_date,p.fetched_at,p.expires_at,f.rank,m.movie_code::text,m.movie_name::text,m.open_date,f.sales_amt,f.audi_cnt,f.sales_acc,f.audi_acc
  from box_office_periods p left join box_office_performances f on f.period_id=p.period_id left join movies m on m.movie_id=f.movie_id
  where p.period_type=p_period_type and p.target_date=p_target_date order by f.rank asc nulls last;
$$;

revoke all on function public.save_box_office_period(text,date,jsonb,timestamptz,timestamptz) from public, anon, authenticated;
revoke all on function public.read_box_office_period(text,date) from public, anon, authenticated;
grant execute on function public.save_box_office_period(text,date,jsonb,timestamptz,timestamptz) to service_role;
grant execute on function public.read_box_office_period(text,date) to service_role;
